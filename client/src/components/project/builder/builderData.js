export const generateWebsiteCode = (websiteData) => {
  // Safely convert website content into valid JavaScript strings.
  const literal = (value, fallback = "") =>
    JSON.stringify(String(value ?? fallback));

  const features = Array.isArray(websiteData.features)
    ? websiteData.features
    : [];

  const navigation = Array.isArray(websiteData.navigation)
    ? websiteData.navigation
    : [];

  // Design settings with safe defaults.
  const theme = websiteData.theme === "dark" ? "dark" : "light";

  const primaryColor = /^#[0-9A-Fa-f]{6}$/.test(
    websiteData.primaryColor || ""
  )
    ? websiteData.primaryColor
    : "#7C3AED";

  const allowedLayouts = [
    "modern",
    "minimalist",
    "saas",
    "editorial",
  ];

  const layoutStyle = allowedLayouts.includes(websiteData.layoutStyle)
    ? websiteData.layoutStyle
    : "modern";

  const allowedSpacing = [
    "compact",
    "comfortable",
    "spacious",
  ];

  const spacing = allowedSpacing.includes(websiteData.spacing)
    ? websiteData.spacing
    : "comfortable";

  const allowedCardStyles = [
    "rounded",
    "sharp",
    "glass",
  ];

  const cardStyle = allowedCardStyles.includes(websiteData.cardStyle)
    ? websiteData.cardStyle
    : "rounded";

  // Generate feature cards.
  const featureCards = features
    .map((feature, index) => {
      const name =
        typeof feature === "string"
          ? feature
          : feature?.name || "Feature";

      const description =
        typeof feature === "string"
          ? "Designed around your website requirements and visitor experience."
          : feature?.description ||
            "Designed around your website requirements and visitor experience.";

      return `
        <article
          key={${index}}
          className={cardClasses}
          style={cardStyleObject}
        >
          <h3 className="mb-3 text-xl font-semibold">
            {${literal(name)}}
          </h3>

          <p style={{ color: colors.muted }}>
            {${literal(description)}}
          </p>
        </article>
      `;
    })
    .join("");

  // Generate navigation links.
  const navigationLinks = navigation
    .map((item, index) => {
      const label =
        typeof item === "string"
          ? item
          : item?.name || item?.label || "Link";

      return `
        <a
          key={${index}}
          href="#"
          className="text-sm transition-opacity hover:opacity-70"
          style={{ color: colors.muted }}
        >
          {${literal(label)}}
        </a>
      `;
    })
    .join("");

  return `import React from "react";

const App = () => {
  // Website content
  const brandName = ${literal(websiteData.brandName, "My Website")};
  const headline = ${literal(websiteData.headline, "Welcome to our website")};
  const description = ${literal(websiteData.description)};
  const audience = ${literal(websiteData.audience)};
  const primaryButton = ${literal(websiteData.primaryButton, "Get Started")};
  const secondaryButton = ${literal(websiteData.secondaryButton, "Learn More")};

  // Design configuration
  const theme = ${literal(theme)};
  const primaryColor = ${literal(primaryColor)};
  const layoutStyle = ${literal(layoutStyle)};
  const spacing = ${literal(spacing)};
  const cardStyle = ${literal(cardStyle)};

  const isDark = theme === "dark";

  // Theme colors
  const colors = {
    background: isDark ? "#09090B" : "#FFFFFF",
    surface: isDark ? "#18181B" : "#F8FAFC",
    text: isDark ? "#FAFAFA" : "#18181B",
    muted: isDark ? "#A1A1AA" : "#64748B",
    border: isDark
      ? "rgba(255,255,255,0.12)"
      : "rgba(0,0,0,0.10)",
  };

  // Layout configuration
  const layoutClasses = {
    modern: "max-w-7xl",
    minimalist: "max-w-5xl",
    saas: "max-w-7xl",
    editorial: "max-w-5xl",
  };

  // Spacing configuration
  const spacingConfig = {
    compact: {
      section: "py-12 md:py-16",
      hero: "py-16 md:py-24",
      gap: "gap-4",
    },
    comfortable: {
      section: "py-16 md:py-24",
      hero: "py-24 md:py-32",
      gap: "gap-6",
    },
    spacious: {
      section: "py-24 md:py-32",
      hero: "py-32 md:py-40",
      gap: "gap-8",
    },
  };

  // Card configuration
  const cardClasses = {
    rounded: "rounded-2xl border",
    sharp: "rounded-none border",
    glass: "rounded-2xl border backdrop-blur-xl",
  }[cardStyle];

  const cardStyleObject = {
    backgroundColor:
      cardStyle === "glass"
        ? isDark
          ? "rgba(255,255,255,0.06)"
          : "rgba(255,255,255,0.65)"
        : colors.surface,
    borderColor: colors.border,
  };

  const pageStyle = {
    backgroundColor: colors.background,
    color: colors.text,
    minHeight: "100vh",
  };

  const buttonStyle = {
    backgroundColor: primaryColor,
    color: "#FFFFFF",
  };

  const accentStyle = {
    color: primaryColor,
  };

  const sectionSpacing = spacingConfig[spacing];

  const headingClass =
    layoutStyle === "editorial"
      ? "font-serif tracking-tight"
      : "font-semibold tracking-tight";

  return (
    <main style={pageStyle} className="transition-colors duration-300">

      {/* Navigation */}
      <nav
        className="mx-auto flex max-w-7xl flex-wrap items-center justify-between gap-5 border-b px-6 py-5 md:px-10"
        style={{ borderColor: colors.border }}
      >
        <h2 className="text-2xl font-bold">
          {brandName}
        </h2>

        <div className="flex flex-wrap items-center gap-6">
          ${navigationLinks}
        </div>

        <button
          className="rounded-xl px-5 py-2.5 text-sm font-semibold transition-opacity hover:opacity-85"
          style={buttonStyle}
        >
          {primaryButton}
        </button>
      </nav>

      {/* Hero */}
      <section
        className={\`mx-auto \${layoutClasses[layoutStyle]} \${sectionSpacing.hero} px-6 text-center md:px-10\`}
      >
        {audience && (
          <span
            className="mb-6 inline-block rounded-full px-4 py-2 text-sm font-medium"
            style={{
              backgroundColor: primaryColor + "18",
              color: primaryColor,
            }}
          >
            {audience}
          </span>
        )}

        <h1
          className={\`mx-auto mb-6 max-w-4xl text-4xl leading-tight md:text-6xl \${headingClass}\`}
        >
          {headline}
        </h1>

        <p
          className="mx-auto mb-10 max-w-2xl text-base leading-8 md:text-lg"
          style={{ color: colors.muted }}
        >
          {description}
        </p>

        <div className="flex flex-wrap justify-center gap-4">
          <button
            className="rounded-xl px-7 py-3.5 font-semibold transition-opacity hover:opacity-85"
            style={buttonStyle}
          >
            {primaryButton}
          </button>

          <button
            className="rounded-xl border px-7 py-3.5 font-semibold transition-opacity hover:opacity-75"
            style={{
              borderColor: colors.border,
              color: colors.text,
            }}
          >
            {secondaryButton}
          </button>
        </div>
      </section>

      {/* Features */}
      ${
        features.length > 0
          ? `
      <section
        className={\`mx-auto \${layoutClasses[layoutStyle]} \${sectionSpacing.section} px-6 md:px-10\`}
        style={{
          backgroundColor: colors.surface,
        }}
      >
        <div className="mb-12 text-center">
          <span
            className="mb-3 block text-sm font-semibold uppercase tracking-widest"
            style={accentStyle}
          >
            What we offer
          </span>

          <h2 className={\`text-3xl md:text-4xl \${headingClass}\`}>
            Capabilities
          </h2>
        </div>

        <div className={\`grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 \${sectionSpacing.gap}\`}>
          ${featureCards}
        </div>
      </section>
      `
          : ""
      }

      {/* Footer */}
      <footer
        className="border-t px-6 py-10 text-center"
        style={{
          borderColor: colors.border,
          color: colors.muted,
        }}
      >
        <p>
          © {new Date().getFullYear()} {brandName}. All rights reserved.
        </p>
      </footer>

    </main>
  );
};

export default App;
`;
};


